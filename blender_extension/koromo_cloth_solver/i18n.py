def tr(message: str, **values) -> str:
    """Translate an interface message using Blender's active locale."""
    translated = bpy.app.translations.pgettext_iface(message)
    if not values:
        return translated
    try:
        return translated.format(**values)
    except (KeyError, ValueError):
        return translated
